//! The host interface's device object: a raw child PDO of the adapter (PLAN.md, M4).
//!
//! Every device object of a PnP stack shares one security descriptor, and the audio stack's
//! must let the audio service in. The host interface needs a stricter one (system,
//! administrators, interactive users), hence a device object of its own: the adapter acts as a
//! bus driver for one child, created with `IoCreateDeviceSecure` and started without a function
//! driver (raw), which registers the device interface `GUID_DEVINTERFACE_HOSTMIC_HOST`.
//!
//! This module handles every request sent to that child: PnP and power as its bus driver,
//! create, close and device control as the host interface. The adapter reports the child in its
//! bus relations ([`report`]) and lets it go when it is removed itself ([`detach`]).
//!
//! With no function driver, the child is also its own power policy owner: it tells the power
//! manager its device power state (`PoSetPowerState`: D0 once started, D3 once gone), and turns
//! each system power change into a device power request for itself (D0 in the working state,
//! D3 in any other, as its capabilities say). It has no hardware: each state is only declared.
//!
//! The PnP manager serializes PnP requests for a device, and removes children before their
//! parent; create, close and device control requests may arrive at any time. A request's IRP
//! may be freed as soon as it is completed: handlers work on a copy of its stack location and
//! hold no reference into it across the completion.

