/// Full access for the system and administrators; read and write (enough for every request)
/// for interactive users, local or remote. Nobody else may open the host interface.
static SDDL: [u16; 42] = wide("D:P(A;;GA;;;SY)(A;;GA;;;BA)(A;;GRGW;;;IU)");

/// `BusQueryDeviceID`, and the only hardware ID.
static DEVICE_ID: [u16; 13] = wide("HOSTMIC\\Host");
/// `BusQueryInstanceID`, by the PDO's slot in [`DEVICES`]: unique in the system, as
/// `UniqueID` (1) says, among the host interfaces present at once, which hold distinct slots.
/// The device keeps its name, and its devnode, across the adapter's reinstallations; with
/// `UniqueID` 0 the PnP manager named it after the adapter's devnode, which every reinstall
/// replaces, and each left a phantom device behind. Never a constant: two adapters' host
/// interfaces with the same instance ID would be a duplicate device (bug check 0xCA).
static INSTANCE_IDS: [[u16; 2]; SLOTS] = [wide("0"), wide("1"), wide("2"), wide("3")];
/// `DeviceTextDescription`: the name Device Manager shows.
static DESCRIPTION: [u16; 23] = wide("hostmic host interface");

/// The child's device extension.
#[repr(C)]
pub struct HostDevice {
    /// The PDO's slot in [`DEVICES`], which names it ([`INSTANCE_IDS`]).
    slot: usize,
    /// Whether the adapter still reports this child; cleared by [`detach`].
    present: AtomicBool,
    /// Whether the adapter reported this child to the PnP manager at least once ([`report`]).
    enumerated: AtomicBool,
    /// Between `IRP_MN_START_DEVICE` and a stop or removal: only then can it be opened.
    started: AtomicBool,
    /// Whether the PnP manager removed this child (`IRP_MN_REMOVE_DEVICE`) since its last start.
    removed: AtomicBool,
    /// Whether the PnP manager reported this child gone (`IRP_MN_SURPRISE_REMOVAL`) since its
    /// last start. Requests on handles still open then must fail, except close, cleanup and
    /// PnP (Microsoft's page on handling a surprise removal request): `ATTACH` and `ADVANCE` are
    /// refused; `DETACH` and the reads stay, so that a host can let go.
    surprise_removed: AtomicBool,
    /// Handles open on the child, from a successful create to its close. While any is open,
    /// the child refuses removal: requests on those handles use the adapter's host link,
    /// which lives in the adapter's device extension.
    open_files: AtomicU32,
    /// From an accepted `IRP_MN_QUERY_REMOVE_DEVICE` to its cancellation or the next start: no
    /// new opens.
    remove_pending: AtomicBool,
    /// The device power state last declared to the power manager ([`declare_power`]):
    /// `PowerDeviceUnspecified` until the first start.
    power: AtomicI32,
    /// Serializes the declarations of [`declare_power`] with the checks that decide them, so
    /// that a device power request handled while the device is being removed cannot declare D0
    /// after the removal's D3. Initialized by [`create`]; `PASSIVE_LEVEL` only.
    power_lock: UnsafeCell<KGUARDED_MUTEX>,
    /// The interface's symbolic link name, registered on the first start. Only PnP requests
    /// for this child and [`delete`] (once nothing else can reach it) touch it, and the PnP
    /// manager serializes them.
    link: UnsafeCell<UNICODE_STRING>,
    /// The adapter's host link: the stream's state and the attached host.
    shared: LinkRef,
}

/// A `UNICODE_STRING` over a static NUL-terminated wide string, the NUL excluded.
fn unicode(text: &'static [u16]) -> UNICODE_STRING {
    let bytes = u16::try_from(size_of_val(text)).unwrap_or(u16::MAX);
    UNICODE_STRING {
        Length: bytes.saturating_sub(2),
        MaximumLength: bytes,
        // Only read by the callee (the C prototypes are not const).
        Buffer: text.as_ptr().cast_mut(),
    }
}

/// Creates the host interface's PDO for the adapter's FDO `parent`.
///
/// # Errors
///
/// The status of `IoCreateDeviceSecure`, or `STATUS_INSUFFICIENT_RESOURCES` when [`DEVICES`]
/// is full.
///
/// # Safety
///
/// `parent` is the adapter's FDO; `PASSIVE_LEVEL`.
pub unsafe fn create(
    parent: PDEVICE_OBJECT,
    shared: LinkRef,
) -> Result<NonNull<DEVICE_OBJECT>, NTSTATUS> {
    // SAFETY: `parent` is a valid device object (caller's contract).
    let driver = unsafe { (*parent).DriverObject };
    let sddl = unicode(&SDDL);
    let mut device: PDEVICE_OBJECT = ptr::null_mut();
    // SAFETY: valid driver object, SDDL string and class GUID that outlive the call, and a
    // writable out-parameter. A PDO must be named: the system generates the name.
    let status = unsafe {
        WdmlibIoCreateDeviceSecure(
            driver,
            size_ulong::<HostDevice>(),
            ptr::null_mut(),
            DEVICE_TYPE,
            FILE_AUTOGENERATED_DEVICE_NAME | FILE_DEVICE_SECURE_OPEN,
            0,
            &raw const sddl,
            &raw const GUID_DEVCLASS_HOSTMIC_HOST,
            &raw mut device,
        )
    };
    if !NT_SUCCESS(status) {
        return Err(status);
    }
    let device = NonNull::new(device).ok_or(STATUS_UNSUCCESSFUL)?;
    // Registered first, as its slot names it. Nothing can send it a request before it is
    // initialized below: the I/O manager refuses opens while `DO_DEVICE_INITIALIZING` is set,
    // and the PnP manager only learns of it from the next bus relations query.
    let Some(slot) = DEVICES.iter().position(|slot| {
        slot.compare_exchange(
            ptr::null_mut(),
            device.as_ptr(),
            Ordering::AcqRel,
            Ordering::Acquire,
        )
        .is_ok()
    }) else {
        // SAFETY: a device object nobody else knows of.
        unsafe { IoDeleteDevice(device.as_ptr()) };
        return Err(STATUS_INSUFFICIENT_RESOURCES);
    };
    // SAFETY: plain data, all zeroes until `KeInitializeGuardedMutex` below.
    let mutex: KGUARDED_MUTEX = unsafe { MaybeUninit::zeroed().assume_init() };
    // SAFETY: a device object just created and not reported to anyone yet: unique access.
    let object = unsafe { &mut *device.as_ptr() };
    // SAFETY: the extension is `size_of::<HostDevice>()` bytes, aligned for pointers, unused.
    unsafe {
        object
            .DeviceExtension
            .cast::<HostDevice>()
            .write(HostDevice {
                slot,
                present: AtomicBool::new(true),
                enumerated: AtomicBool::new(false),
                started: AtomicBool::new(false),
                removed: AtomicBool::new(false),
                surprise_removed: AtomicBool::new(false),
                open_files: AtomicU32::new(0),
                remove_pending: AtomicBool::new(false),
                power: AtomicI32::new(_DEVICE_POWER_STATE::PowerDeviceUnspecified),
                power_lock: UnsafeCell::new(mutex),
                link: UnsafeCell::new(UNICODE_STRING {
                    Length: 0,
                    MaximumLength: 0,
                    Buffer: ptr::null_mut(),
                }),
                shared,
            });
    };
    {
        // SAFETY: the extension was just written and is not shared yet.
        let this = unsafe { &*object.DeviceExtension.cast::<HostDevice>() };
        // SAFETY: a guarded mutex in the device extension, which does not move while the
        // device object lives; PASSIVE_LEVEL.
        unsafe { KeInitializeGuardedMutex(this.power_lock.get()) };
    }
    // Power requests at PASSIVE_LEVEL; the device is ready for requests.
    object.Flags |= DO_POWER_PAGABLE;
    object.Flags &= !DO_DEVICE_INITIALIZING;
    Ok(device)
}

/// Whether `device` is a host interface PDO (as opposed to the adapter's FDO). Compares
/// addresses only.
#[must_use]
pub fn owns(device: PDEVICE_OBJECT) -> bool {
    !device.is_null()
        && DEVICES
            .iter()
            .any(|slot| slot.load(Ordering::Acquire) == device)
}

/// The [`HostDevice`] of a host interface PDO.
///
/// # Safety
///
/// [`owns`] is true for `device`, which is not deleted yet.
unsafe fn this<'a>(device: PDEVICE_OBJECT) -> &'a HostDevice {
    // SAFETY: a valid device object (caller's contract); a raw field read.
    let extension = unsafe { (*device).DeviceExtension };
    // SAFETY: the extension was initialized by `create` and lives as long as the device
    // object; all shared access goes through atomics or the `UnsafeCell`.
    unsafe { &*extension.cast::<HostDevice>() }
}

/// The interface's link name.
///
/// # Safety
///
/// Called from a PnP request for the device whose extension is `this` (serialized), or from
/// [`delete`] once nothing else can reach it: no other access at the same time.
#[allow(
    clippy::mut_from_ref,
    reason = "the UnsafeCell's accesses are serialized by the PnP manager"
)]
unsafe fn link(this: &HostDevice) -> &mut UNICODE_STRING {
    // SAFETY: the caller's contract.
    unsafe { &mut *this.link.get() }
}

/// Adds `child` to the bus relations of the adapter's `IRP_MN_QUERY_DEVICE_RELATIONS`
/// (`BusRelations`) before it goes down the stack, keeping any relations already there.
///
/// # Errors
///
/// `STATUS_INSUFFICIENT_RESOURCES`, with the request failed: its status set to that, and the
/// relations an upper driver put there released (their references and the structure), as a
/// failed request carries none; the caller completes it. Passing the request down unchanged
/// would report the relations without the child, which the PnP manager would take for the
/// child's departure and remove it.
///
/// # Safety
///
/// `irp` is the adapter's bus relations query, in its dispatch routine; `child` is the live
/// host interface PDO; `PASSIVE_LEVEL`.
pub unsafe fn report(irp: *mut IRP, child: NonNull<DEVICE_OBJECT>) -> Result<(), NTSTATUS> {
    // SAFETY: a valid IRP owned by this driver for the call (caller's contract).
    let irp = unsafe { &mut *irp };
    // SAFETY: `Status` is the union's member for a request being processed.
    let status = unsafe { irp.IoStatus.__bindgen_anon_1.Status };
    // On success, `Information` is null or a `DEVICE_RELATIONS` from paged pool that the
    // request's current owner owns (from a driver above); otherwise there is none.
    let old = if NT_SUCCESS(status) {
        irp.IoStatus.Information as *mut DEVICE_RELATIONS
    } else {
        ptr::null_mut()
    };
    let old_objects: &[PDEVICE_OBJECT] = if old.is_null() {
        &[]
    } else {
        // SAFETY: as above.
        let old = unsafe { &*old };
        // SAFETY: a `DEVICE_RELATIONS` holds `Count` object pointers from `Objects` on.
        unsafe { slice::from_raw_parts(old.Objects.as_ptr(), old.Count as usize) }
    };
    // SAFETY: the caller's contract.
    let this = unsafe { this(child.as_ptr()) };
    if old_objects.contains(&child.as_ptr()) {
        this.enumerated.store(true, Ordering::Release);
        return Ok(());
    }
    let count = old_objects.len() + 1;
    let bytes = offset_of!(DEVICE_RELATIONS, Objects) + count * size_of::<PDEVICE_OBJECT>();
    // SAFETY: PASSIVE_LEVEL; paged pool, as the PnP manager frees it.
    let new = unsafe { ExAllocatePool2(POOL_FLAG_PAGED, bytes as u64, POOL_TAG) }
        .cast::<DEVICE_RELATIONS>();
    if new.is_null() {
        for &object in old_objects {
            // SAFETY: each reported object carries a reference for the PnP manager, which a
            // failed request does not hand over.
            unsafe { ObfDereferenceObject(object.cast()) };
        }
        if !old.is_null() {
            // SAFETY: the old relations came from the pool; `old_objects` is not used after.
            unsafe { ExFreePool(old.cast()) };
        }
        irp.IoStatus.Information = 0;
        irp.IoStatus.__bindgen_anon_1.Status = STATUS_INSUFFICIENT_RESOURCES;
        return Err(STATUS_INSUFFICIENT_RESOURCES);
    }
    // SAFETY: a fresh, zeroed allocation with room for a count and `count` object pointers.
    let relations = unsafe { &mut *new };
    relations.Count = u32::try_from(count).unwrap_or(u32::MAX);
    // SAFETY: as above: `count` pointers from `Objects` on.
    let objects = unsafe { slice::from_raw_parts_mut(relations.Objects.as_mut_ptr(), count) };
    // The old pointers keep their references; the child gets one for the PnP manager.
    objects[..old_objects.len()].copy_from_slice(old_objects);
    objects[old_objects.len()] = child.as_ptr();
    // SAFETY: `child` is a live device object.
    unsafe { ObfReferenceObject(child.as_ptr().cast()) };
    if !old.is_null() {
        // SAFETY: the old relations came from the pool and nothing refers to them any more.
        unsafe { ExFreePool(old.cast()) };
    }
    irp.IoStatus.Information = new as u64;
    irp.IoStatus.__bindgen_anon_1.Status = STATUS_SUCCESS;
    this.enumerated.store(true, Ordering::Release);
    Ok(())
}

/// The adapter goes away: `child` is no longer reported. It is deleted now if the PnP manager
/// already removed it (it removes the children it knows before their parent) or never learned
/// of it; otherwise when the PnP manager removes it.
///
/// # Safety
///
/// `child` is the live host interface PDO; called from the adapter's `IRP_MN_REMOVE_DEVICE`.
pub unsafe fn detach(child: NonNull<DEVICE_OBJECT>) {
    // SAFETY: the caller's contract.
    let this = unsafe { this(child.as_ptr()) };
    this.present.store(false, Ordering::Release);
    if this.removed.load(Ordering::Acquire) || !this.enumerated.load(Ordering::Acquire) {
        // SAFETY: removed (or never known to the PnP manager) and no longer reported: nothing
        // will send it requests.
        unsafe { delete(child.as_ptr()) };
    }
}

/// Unregisters the device, frees the interface's link name and deletes the device object.
///
/// # Safety
///
/// `device` is a host interface PDO that the PnP manager removed (or never learned of) and
/// that the adapter no longer reports.
unsafe fn delete(device: PDEVICE_OBJECT) {
    // SAFETY: the caller's contract.
    let this = unsafe { this(device) };
    // SAFETY: nothing else can reach the device any more.
    let link = unsafe { link(this) };
    if !link.Buffer.is_null() {
        // SAFETY: allocated by `IoRegisterDeviceInterface`.
        unsafe { RtlFreeUnicodeString(link) };
    }
    for slot in &DEVICES {
        let _ = slot.compare_exchange(device, ptr::null_mut(), Ordering::AcqRel, Ordering::Acquire);
    }
    println!("hostmic: host interface device deleted");
    // SAFETY: the caller's contract; nothing uses the extension after this.
    unsafe { IoDeleteDevice(device) };
}

/// Every request sent to a host interface PDO.
///
/// # Safety
///
/// Called from the driver's dispatch routine with a request for a device that [`owns`].
pub unsafe fn dispatch(device: PDEVICE_OBJECT, irp: *mut IRP) -> NTSTATUS {
    // SAFETY: an IRP being dispatched to this driver.
    let stack = unsafe { current_stack_location(irp) };
    // SAFETY: its current stack location is valid until the request completes; copied, so
    // that nothing refers into the IRP afterwards.
    let stack: IO_STACK_LOCATION = unsafe { stack.read() };
    match u32::from(stack.MajorFunction) {
        // SAFETY: a PnP request for this device.
        IRP_MJ_PNP => unsafe { pnp(device, irp, &stack) },
        // SAFETY: a power request for this device.
        IRP_MJ_POWER => unsafe { power(device, irp, &stack) },
        // No WMI: leave the request as the I/O manager initialized it.
        // SAFETY: as above.
        IRP_MJ_SYSTEM_CONTROL => unsafe { complete_unchanged(irp) },
        IRP_MJ_CREATE => {
            // SAFETY: the caller's contract.
            let status = create_file(unsafe { this(device) }, &stack);
            // SAFETY: a request owned by this driver.
            unsafe { complete(irp, status, 0) }
        }
        IRP_MJ_CLEANUP | IRP_MJ_CLOSE => {
            // The attached host's handle going away detaches it: the host exited or crashed.
            // At cleanup (last handle closed) normally; at close too, for an `ATTACH` that
            // was still in flight when the handle was closed.
            // SAFETY: the caller's contract.
            let this = unsafe { this(device) };
            this.shared.get().detach(stack.FileObject, None);
            if u32::from(stack.MajorFunction) == IRP_MJ_CLOSE {
                // The last request on this handle: it no longer holds the device back.
                this.open_files.fetch_sub(1, Ordering::SeqCst);
            }
            // SAFETY: a request owned by this driver.
            unsafe { complete(irp, STATUS_SUCCESS, 0) }
        }
        // SAFETY: a device control request owned by this driver.
        IRP_MJ_DEVICE_CONTROL => unsafe { device_control(device, irp, &stack) },
        // SAFETY: a request owned by this driver.
        _ => unsafe { complete(irp, STATUS_INVALID_DEVICE_REQUEST, 0) },
    }
}

/// Completes `irp` with `status` and `information`; returns `status`.
///
/// # Safety
///
/// `irp` is owned by this driver and not completed yet; nothing touches it afterwards.
pub unsafe fn complete(irp: *mut IRP, status: NTSTATUS, information: u64) -> NTSTATUS {
    {
        // SAFETY: the caller's contract.
        let irp = unsafe { &mut *irp };
        irp.IoStatus.__bindgen_anon_1.Status = status;
        irp.IoStatus.Information = information;
    }
    // SAFETY: the caller's contract; the reference above is gone.
    unsafe { IofCompleteRequest(irp, IO_NO_INCREMENT) };
    status
}

/// Completes `irp` with the status and information it already carries: what a bus driver does
/// with a request it does not handle.
///
/// # Safety
///
/// As [`complete`].
unsafe fn complete_unchanged(irp: *mut IRP) -> NTSTATUS {
    let status = {
        // SAFETY: the caller's contract.
        let io_status = unsafe { &(*irp).IoStatus };
        // SAFETY: `Status` is the union's member for a request being processed.
        unsafe { io_status.__bindgen_anon_1.Status }
    };
    // SAFETY: the caller's contract; the reference above is gone.
    unsafe { IofCompleteRequest(irp, IO_NO_INCREMENT) };
    status
}

/// Completes `irp` with `status`, leaving `Information` as it is (PnP requests that carry no
/// reply data, where `Information` may hold an upper driver's).
///
/// # Safety
///
/// As [`complete`].
unsafe fn complete_status(irp: *mut IRP, status: NTSTATUS) -> NTSTATUS {
    {
        // SAFETY: the caller's contract.
        let irp = unsafe { &mut *irp };
        irp.IoStatus.__bindgen_anon_1.Status = status;
    }
    // SAFETY: the caller's contract; the reference above is gone.
    unsafe { IofCompleteRequest(irp, IO_NO_INCREMENT) };
    status
}

/// PnP requests, as the child's bus driver.
///
/// # Safety
///
/// A PnP request owned by this driver for `device`, whose stack location is copied in
/// `stack`; `PASSIVE_LEVEL`.
unsafe fn pnp(device: PDEVICE_OBJECT, irp: *mut IRP, stack: &IO_STACK_LOCATION) -> NTSTATUS {
    let status = match u32::from(stack.MinorFunction) {
        // SAFETY: a start request for `device`.
        IRP_MN_START_DEVICE => unsafe { start(device) },
        IRP_MN_QUERY_STOP_DEVICE | IRP_MN_CANCEL_STOP_DEVICE => STATUS_SUCCESS,
        IRP_MN_QUERY_REMOVE_DEVICE => {
            // SAFETY: a live device of this module.
            let this = unsafe { this(device) };
            // Pending first, then count: a create counts first, then checks (`create_file`),
            // so one of the two sees the other.
            this.remove_pending.store(true, Ordering::SeqCst);
            let open = this.open_files.load(Ordering::SeqCst);
            if open == 0 {
                STATUS_SUCCESS
            } else {
                this.remove_pending.store(false, Ordering::SeqCst);
                println!("hostmic: host interface removal refused: {open} handle(s) open");
                STATUS_DEVICE_BUSY
            }
        }
        IRP_MN_CANCEL_REMOVE_DEVICE => {
            // SAFETY: a live device of this module.
            unsafe { this(device) }
                .remove_pending
                .store(false, Ordering::SeqCst);
            STATUS_SUCCESS
        }
        IRP_MN_STOP_DEVICE => {
            // SAFETY: a live device of this module.
            unsafe { this(device) }
                .started
                .store(false, Ordering::Release);
            STATUS_SUCCESS
        }
        IRP_MN_SURPRISE_REMOVAL => {
            // SAFETY: a live device of this module.
            unsafe { this(device) }
                .surprise_removed
                .store(true, Ordering::Release);
            // SAFETY: a PnP request for this device.
            unsafe { stop(device) };
            STATUS_SUCCESS
        }
        IRP_MN_REMOVE_DEVICE => {
            // SAFETY: a live device of this module.
            let this = unsafe { this(device) };
            // Removed before `stop` declares D3, as a surprise removal is: a device power
            // request handled meanwhile then sees the device gone (`power_lock`).
            this.removed.store(true, Ordering::Release);
            // SAFETY: a PnP request for this device.
            unsafe { stop(device) };
            if !this.present.load(Ordering::Acquire) {
                // SAFETY: removed and no longer reported by the adapter. As in Microsoft's
                // bus samples, deleted before the request completes: the I/O manager keeps
                // the object alive while it references it. `this` is not used afterwards.
                unsafe { delete(device) };
            }
            STATUS_SUCCESS
        }
        // SAFETY: the copied stack location of a capabilities query.
        IRP_MN_QUERY_CAPABILITIES => unsafe { capabilities(stack) },
        IRP_MN_QUERY_ID => {
            // SAFETY: the parameters of an ID query.
            let id_type = unsafe { stack.Parameters.QueryId.IdType };
            let (text, extra_nuls): (&'static [u16], usize) = match id_type {
                BUS_QUERY_ID_TYPE::BusQueryDeviceID => (&DEVICE_ID, 0),
                // A multi-string: one more NUL.
                BUS_QUERY_ID_TYPE::BusQueryHardwareIDs => (&DEVICE_ID, 1),
                BUS_QUERY_ID_TYPE::BusQueryInstanceID => {
                    // SAFETY: a live device of this module.
                    let slot = unsafe { this(device) }.slot;
                    match INSTANCE_IDS.get(slot) {
                        Some(id) => (id, 0),
                        // Not reached: `create` takes a slot of `DEVICES`.
                        // SAFETY: a PnP request owned by this driver.
                        None => return unsafe { complete_unchanged(irp) },
                    }
                }
                // SAFETY: a PnP request owned by this driver.
                _ => return unsafe { complete_unchanged(irp) },
            };
            // SAFETY: a PnP request owned by this driver, PASSIVE_LEVEL.
            return unsafe { reply_text(irp, text, extra_nuls) };
        }
        IRP_MN_QUERY_DEVICE_TEXT => {
            // SAFETY: the parameters of a device text query.
            let text_type = unsafe { stack.Parameters.QueryDeviceText.DeviceTextType };
            return if text_type == DEVICE_TEXT_TYPE::DeviceTextDescription {
                // SAFETY: a PnP request owned by this driver, PASSIVE_LEVEL.
                unsafe { reply_text(irp, &DESCRIPTION, 0) }
            } else {
                // SAFETY: a PnP request owned by this driver.
                unsafe { complete_unchanged(irp) }
            };
        }
        IRP_MN_QUERY_DEVICE_RELATIONS => {
            // SAFETY: the parameters of a relations query.
            let relation = unsafe { stack.Parameters.QueryDeviceRelations.Type };
            return if relation == _DEVICE_RELATION_TYPE::TargetDeviceRelation {
                // SAFETY: a PnP request owned by this driver for `device`, PASSIVE_LEVEL.
                unsafe { reply_target_relation(irp, device) }
            } else {
                // SAFETY: a PnP request owned by this driver.
                unsafe { complete_unchanged(irp) }
            };
        }
        // SAFETY: a PnP request owned by this driver.
        _ => return unsafe { complete_unchanged(irp) },
    };
    // SAFETY: a PnP request owned by this driver.
    unsafe { complete_status(irp, status) }
}

/// `IRP_MN_START_DEVICE`: registers the interface on the first start, then enables it; the
/// device can then be opened.
///
/// # Safety
///
/// A start request for `device`.
unsafe fn start(device: PDEVICE_OBJECT) -> NTSTATUS {
    // SAFETY: a live device of this module.
    let this = unsafe { this(device) };
    // SAFETY: a PnP request for this device.
    let link = unsafe { link(this) };
    if link.Buffer.is_null() {
        // SAFETY: a PDO being started, a valid GUID, no reference string, and a writable link
        // name that `delete` frees.
        let status = unsafe {
            IoRegisterDeviceInterface(device, &raw const INTERFACE_GUID, ptr::null_mut(), link)
        };
        if !NT_SUCCESS(status) {
            println!("hostmic: host interface registration failed: {status:#010x}");
            return status;
        }
    }
    // SAFETY: a link name registered above.
    let status = unsafe { IoSetDeviceInterfaceState(link, 1) };
    println!("hostmic: host interface enabled: {status:#010x}");
    if NT_SUCCESS(status) {
        // Started: in D0, as the power manager must be told by the device's bus driver.
        // SAFETY: a live device of this module, PASSIVE_LEVEL.
        unsafe {
            declare_power(device, this, _DEVICE_POWER_STATE::PowerDeviceD0, |_, _| {
                true
            });
        };
        // A device disabled and enabled again in Device Manager is queried for removal,
        // removed, then started, with no cancellation in between: both flags go back here,
        // before opens are allowed again.
        this.removed.store(false, Ordering::Release);
        this.surprise_removed.store(false, Ordering::Release);
        this.remove_pending.store(false, Ordering::SeqCst);
        this.started.store(true, Ordering::Release);
    }
    status
}

/// Surprise removal or removal: no more opens, interface disabled (if it was ever registered),
/// device in D3 (if it was ever started).
///
/// # Safety
///
/// A PnP request for `device`; `PASSIVE_LEVEL`.
unsafe fn stop(device: PDEVICE_OBJECT) {
    // SAFETY: a live device of this module.
    let this = unsafe { this(device) };
    this.started.store(false, Ordering::Release);
    // SAFETY: the caller's contract.
    let link = unsafe { link(this) };
    if !link.Buffer.is_null() {
        // SAFETY: a registered link name. Failing to disable it changes nothing more.
        let status = unsafe { IoSetDeviceInterfaceState(link, 0) };
        println!("hostmic: host interface disabled: {status:#010x}");
    }
    // Not for a device never started, nor a second time after a surprise removal.
    // SAFETY: a live device of this module, PASSIVE_LEVEL.
    unsafe {
        declare_power(
            device,
            this,
            _DEVICE_POWER_STATE::PowerDeviceD3,
            |_, current| {
                current != _DEVICE_POWER_STATE::PowerDeviceUnspecified
                    && current != _DEVICE_POWER_STATE::PowerDeviceD3
            },
        );
    }
}

/// Declares `state` as the device's power state to the power manager (`PoSetPowerState`) and
/// records it, if `when` (given the device and the state last declared) allows it: both under
/// the device's `power_lock`, so that what `when` checks holds for the declaration.
///
/// # Safety
///
/// `device` is a live host interface PDO, whose extension is `this`; `PASSIVE_LEVEL`.
unsafe fn declare_power(
    device: PDEVICE_OBJECT,
    this: &HostDevice,
    state: DEVICE_POWER_STATE,
    when: impl FnOnce(&HostDevice, DEVICE_POWER_STATE) -> bool,
) {
    with_lock(&this.power_lock, || {
        if !when(this, this.power.load(Ordering::Acquire)) {
            return;
        }
        // SAFETY: the caller's contract (PoSetPowerState: IRQL <= APC_LEVEL). The previous
        // state it returns is not needed.
        unsafe {
            PoSetPowerState(
                device,
                _POWER_STATE_TYPE::DevicePowerState,
                POWER_STATE { DeviceState: state },
            )
        };
        this.power.store(state, Ordering::Release);
    });
}

/// `IRP_MN_QUERY_CAPABILITIES`: a raw device, installed silently, without wake.
///
/// # Safety
///
/// The copied stack location of a capabilities query, whose structure the PnP manager owns
/// until the request completes.
unsafe fn capabilities(stack: &IO_STACK_LOCATION) -> NTSTATUS {
    // SAFETY: the parameters of a capabilities query.
    let capabilities = unsafe { stack.Parameters.DeviceCapabilities.Capabilities };
    // SAFETY: the PnP manager passes a structure it owns for the request, possibly null; the
    // reference ends before the request completes.
    let Some(capabilities) = (unsafe { capabilities.as_mut() }) else {
        return STATUS_INVALID_PARAMETER;
    };
    if capabilities.Version != 1
        || usize::from(capabilities.Size) < size_of::<DEVICE_CAPABILITIES>()
    {
        return STATUS_UNSUCCESSFUL;
    }
    capabilities.set_RawDeviceOK(1);
    capabilities.set_SilentInstall(1);
    capabilities.set_SurpriseRemovalOK(1);
    // The instance ID is unique in the system (`INSTANCE_IDS`).
    capabilities.set_UniqueID(1);
    let working = _SYSTEM_POWER_STATE::PowerSystemWorking as usize;
    for (state, device_state) in capabilities.DeviceState.iter_mut().enumerate() {
        if state == working {
            *device_state = _DEVICE_POWER_STATE::PowerDeviceD0;
        } else if state > working {
            *device_state = _DEVICE_POWER_STATE::PowerDeviceD3;
        }
    }
    capabilities.DeviceWake = _DEVICE_POWER_STATE::PowerDeviceUnspecified;
    capabilities.SystemWake = _SYSTEM_POWER_STATE::PowerSystemUnspecified;
    STATUS_SUCCESS
}

/// Completes a PnP query with a copy of `text` in paged pool, which the PnP manager frees,
/// followed by `extra_nuls` more NULs (1 for a multi-string).
///
/// # Safety
///
/// A PnP request owned by this driver; `PASSIVE_LEVEL`.
unsafe fn reply_text(irp: *mut IRP, text: &'static [u16], extra_nuls: usize) -> NTSTATUS {
    let units = text.len() + extra_nuls;
    // SAFETY: PASSIVE_LEVEL; paged pool, zeroed by `ExAllocatePool2`.
    let copy =
        unsafe { ExAllocatePool2(POOL_FLAG_PAGED, (units * size_of::<u16>()) as u64, POOL_TAG) };
    if copy.is_null() {
        // SAFETY: the caller's contract.
        return unsafe { complete(irp, STATUS_INSUFFICIENT_RESOURCES, 0) };
    }
    {
        // SAFETY: `copy` holds `units` zeroed UTF-16 units, aligned by the pool.
        let units = unsafe { slice::from_raw_parts_mut(copy.cast::<u16>(), units) };
        units[..text.len()].copy_from_slice(text);
    }
    // SAFETY: the caller's contract.
    unsafe { complete(irp, STATUS_SUCCESS, copy as u64) }
}

/// Completes `IRP_MN_QUERY_DEVICE_RELATIONS` (`TargetDeviceRelation`) with the device itself.
///
/// # Safety
///
/// A PnP request owned by this driver for `device`; `PASSIVE_LEVEL`.
unsafe fn reply_target_relation(irp: *mut IRP, device: PDEVICE_OBJECT) -> NTSTATUS {
    // SAFETY: PASSIVE_LEVEL; paged pool, as the PnP manager frees it.
    let relations = unsafe {
        ExAllocatePool2(
            POOL_FLAG_PAGED,
            size_of::<DEVICE_RELATIONS>() as u64,
            POOL_TAG,
        )
    }
    .cast::<DEVICE_RELATIONS>();
    if relations.is_null() {
        // SAFETY: the caller's contract.
        return unsafe { complete(irp, STATUS_INSUFFICIENT_RESOURCES, 0) };
    }
    {
        // SAFETY: a fresh allocation of one `DEVICE_RELATIONS`, zeroed.
        let relations = unsafe { &mut *relations };
        relations.Count = 1;
        relations.Objects[0] = device;
    }
    // SAFETY: a live device object; the PnP manager releases this reference.
    unsafe { ObfReferenceObject(device.cast()) };
    // SAFETY: the caller's contract.
    unsafe { complete(irp, STATUS_SUCCESS, relations as u64) }
}

/// Power requests, as the child's bus driver and power policy owner. The device has no
/// hardware: it accepts every state; a system power request (set or query) becomes a device
/// power request of the same kind ([`system_power`]), and a device power change is declared
/// ([`declare_power`]). No wake (`IRP_MN_WAIT_WAKE` keeps the I/O manager's
/// `STATUS_NOT_SUPPORTED`).
///
/// # Safety
///
/// A power request owned by this driver for `device`, whose stack location is copied in
/// `stack`; `PASSIVE_LEVEL` (`DO_POWER_PAGABLE`).
unsafe fn power(device: PDEVICE_OBJECT, irp: *mut IRP, stack: &IO_STACK_LOCATION) -> NTSTATUS {
    // SAFETY: the parameters of a power request.
    let parameters = unsafe { stack.Parameters.Power };
    match (u32::from(stack.MinorFunction), parameters.Type) {
        (IRP_MN_SET_POWER | IRP_MN_QUERY_POWER, _POWER_STATE_TYPE::SystemPowerState) => {
            // SAFETY: a system power request: `SystemState` is the union's member.
            let system = unsafe { parameters.State.SystemState };
            // SAFETY: the caller's contract.
            unsafe { system_power(device, irp, stack.MinorFunction, system) }
        }
        (IRP_MN_SET_POWER, _POWER_STATE_TYPE::DevicePowerState) => {
            // SAFETY: a device power request: `DeviceState` is the union's member.
            let state = unsafe { parameters.State.DeviceState };
            // SAFETY: a live device of this module.
            let this = unsafe { this(device) };
            let valid = (_DEVICE_POWER_STATE::PowerDeviceD0..=_DEVICE_POWER_STATE::PowerDeviceD3)
                .contains(&state);
            if valid {
                // Declared only for a device in place: a request that a system power change
                // sent just before a (surprise) removal leaves the removal's D3. A bus driver
                // may even fail a power-up of a removed device; this one has nothing to fail.
                // SAFETY: a live device of this module, PASSIVE_LEVEL.
                unsafe {
                    declare_power(device, this, state, |this, _| {
                        !this.removed.load(Ordering::Acquire)
                            && !this.surprise_removed.load(Ordering::Acquire)
                    });
                };
            }
            // SAFETY: the caller's contract.
            unsafe { complete_status(irp, STATUS_SUCCESS) }
        }
        // SAFETY: the caller's contract.
        (IRP_MN_QUERY_POWER, _) => unsafe { complete_status(irp, STATUS_SUCCESS) },
        // SAFETY: the caller's contract.
        _ => unsafe { complete_unchanged(irp) },
    }
}

/// The device power state for the system power state `system`, as the capabilities report it
/// ([`capabilities`]): D0 in the working state, D3 in any other.
fn device_state_for(system: SYSTEM_POWER_STATE) -> DEVICE_POWER_STATE {
    if system == _SYSTEM_POWER_STATE::PowerSystemWorking {
        _DEVICE_POWER_STATE::PowerDeviceD0
    } else {
        _DEVICE_POWER_STATE::PowerDeviceD3
    }
}

/// `IRP_MN_SET_POWER` or `IRP_MN_QUERY_POWER` (`minor`) for a system power state. As the power
/// policy owner, the device requests a device power request of the same kind for the matching
/// state from the power manager (`PoRequestPowerIrp`), even when it is already in that state,
/// and completes the system request once that one is done ([`system_power_done`]). Nothing to
/// request when the device is not started (the next start declares D0). A system set-power
/// request cannot fail: it completes with success either way; a query, with its device query's
/// status (success: nothing here can refuse a state).
///
/// # Safety
///
/// A power request owned by this driver for `device`; `PASSIVE_LEVEL`.
unsafe fn system_power(
    device: PDEVICE_OBJECT,
    irp: *mut IRP,
    minor: u8,
    system: SYSTEM_POWER_STATE,
) -> NTSTATUS {
    // SAFETY: a live device of this module.
    let this = unsafe { this(device) };
    if !this.started.load(Ordering::Acquire) {
        // SAFETY: the caller's contract.
        return unsafe { complete_status(irp, STATUS_SUCCESS) };
    }
    // Pending before the request: the device power request goes to this same device, which
    // completes it at once, so `system_power_done` may complete `irp` before
    // `PoRequestPowerIrp` returns.
    // SAFETY: the caller's contract; not completed yet.
    unsafe { mark_pending(irp) };
    // SAFETY: a live device object; a completion routine of the required type, whose context
    // is `irp`, which this driver owns until that routine completes it; no IRP pointer wanted.
    let status = unsafe {
        PoRequestPowerIrp(
            device,
            minor,
            POWER_STATE {
                DeviceState: device_state_for(system),
            },
            Some(system_power_done),
            irp.cast(),
            ptr::null_mut(),
        )
    };
    // Any other status: no request was sent, and the completion routine will not be called.
    if status != STATUS_PENDING {
        println!("hostmic: host interface device power request failed: {status:#010x}");
        // SAFETY: `irp` is still this driver's (above). Marked pending, it may complete here and
        // return STATUS_PENDING.
        unsafe { complete_status(irp, STATUS_SUCCESS) };
    }
    STATUS_PENDING
}

/// Completion routine of the device power request [`system_power`] sent: completes the system
/// power request, its `context`: a set-power one with success, a query with the device query's
/// status.
///
/// # Safety
///
/// Called by the power manager, at `PASSIVE_LEVEL` or `DISPATCH_LEVEL`, once that request is
/// done; `context` is the system power request, owned by this driver and not completed yet.
unsafe extern "C" fn system_power_done(
    _device: PDEVICE_OBJECT,
    minor: u8,
    _state: POWER_STATE,
    context: PVOID,
    io_status: PIO_STATUS_BLOCK,
) {
    // SAFETY: the power manager passes the device request's status block, valid for the call,
    // possibly null.
    let status = match unsafe { io_status.as_ref() } {
        // SAFETY: `Status` is the union's member for a completed request.
        Some(io_status) => unsafe { io_status.__bindgen_anon_1.Status },
        None => STATUS_SUCCESS,
    };
    if !NT_SUCCESS(status) {
        println!("hostmic: host interface device power request completed with {status:#010x}");
    }
    let status = if u32::from(minor) == IRP_MN_QUERY_POWER {
        status
    } else {
        STATUS_SUCCESS
    };
    // SAFETY: the caller's contract; nothing touches it afterwards. `IofCompleteRequest` runs
    // at either IRQL.
    unsafe { complete_status(context.cast(), status) };
}

/// `IoMarkIrpPending`, an inline function of `wdm.h` that `wdk-sys` does not bind.
///
/// # Safety
///
/// `irp` is owned by this driver and not completed yet.
unsafe fn mark_pending(irp: *mut IRP) {
    // SAFETY: the caller's contract.
    let location = unsafe { current_stack_location(irp) };
    #[allow(
        clippy::cast_possible_truncation,
        reason = "SL_PENDING_RETURNED is 0x01"
    )]
    let pending = SL_PENDING_RETURNED as u8;
    // SAFETY: the current stack location of a request being processed.
    unsafe { (*location).Control |= pending };
}

/// `IRP_MJ_CREATE`: the interface itself only, while started, never relative to another
/// handle (which could skip the access check) nor with a name below it.
fn create_file(this: &HostDevice, stack: &IO_STACK_LOCATION) -> NTSTATUS {
    if !this.started.load(Ordering::Acquire) || this.removed.load(Ordering::Acquire) {
        return STATUS_NO_SUCH_DEVICE;
    }
    // SAFETY: a create request carries its file object, valid until the request completes;
    // the reference ends before.
    let Some(file) = (unsafe { stack.FileObject.as_ref() }) else {
        return STATUS_INVALID_PARAMETER;
    };
    if !file.RelatedFileObject.is_null() {
        return STATUS_ACCESS_DENIED;
    }
    if file.FileName.Length != 0 {
        return STATUS_OBJECT_PATH_NOT_FOUND;
    }
    // SAFETY: the current stack location of a create request, at PASSIVE_LEVEL.
    if !unsafe { create_allowed(stack) } {
        return STATUS_ACCESS_DENIED;
    }
    // Count first, then check for a pending removal (`IRP_MN_QUERY_REMOVE_DEVICE` does the
    // reverse): either the removal sees this handle, or this open sees the removal.
    this.open_files.fetch_add(1, Ordering::SeqCst);
    if this.remove_pending.load(Ordering::SeqCst) {
        this.open_files.fetch_sub(1, Ordering::SeqCst);
        return STATUS_DELETE_PENDING;
    }
    STATUS_SUCCESS
}

/// Whether a create request may open the host interface: one that asks for writing, which
/// `ATTACH`, `ADVANCE` and `DETACH` need, must come from a token of at least medium integrity
/// ([`host::open_allowed`]). The device object has no integrity label (`IoCreateDeviceSecure`
/// takes a DACL only), and in the test VM a process at low integrity could open it for writing
/// despite Windows' rule that unlabeled objects are treated as medium; this applies that rule.
///
/// # Safety
///
/// `stack` is the current stack location of an `IRP_MJ_CREATE` request, at `PASSIVE_LEVEL`.
unsafe fn create_allowed(stack: &IO_STACK_LOCATION) -> bool {
    // SAFETY: the parameters of a create request (the caller's contract).
    let security = unsafe { stack.Parameters.Create.SecurityContext };
    // SAFETY: the I/O manager's security context, valid while the request is processed.
    let Some(security) = (unsafe { security.as_ref() }) else {
        return false;
    };
    // SAFETY: its access state, valid while the request is processed.
    let Some(state) = (unsafe { security.AccessState.as_ref() }) else {
        return false;
    };
    // What was asked (generic rights included) and what the I/O manager's check granted.
    let access = security.DesiredAccess
        | state.OriginalDesiredAccess
        | state.RemainingDesiredAccess
        | state.PreviouslyGrantedAccess;
    if !host::asks_write(access) {
        // No writing asked for: no token to read.
        return true;
    }
    // Both tokens of the subject: the process's, and the thread's impersonation token if there
    // is one (`SeQuerySubjectContextToken`, a macro, picks the latter alone). Requiring both
    // keeps a low-integrity process holding a medium identification token from writing.
    let subject = &state.SubjectSecurityContext;
    // SAFETY: the subject context's primary token, referenced while the request is processed;
    // PASSIVE_LEVEL.
    let primary = unsafe { integrity_level(subject.PrimaryToken) };
    let level = if subject.ClientToken.is_null() {
        primary
    } else {
        // SAFETY: as above, the impersonation token.
        let client = unsafe { integrity_level(subject.ClientToken) };
        match (primary, client) {
            (Some(primary), Some(client)) => Some(primary.min(client)),
            _ => None,
        }
    };
    host::open_allowed(access, level)
}

/// The integrity level of `token` (`SECURITY_MANDATORY_*_RID`), or `None` when it cannot be
/// read.
///
/// For `TokenIntegrityLevel`, `SeQueryInformationToken` writes the level itself, a `DWORD`, in
/// the pointer it is given ("The buffer receives a DWORD value (not a pointer to it)"), unlike
/// the classes whose information it allocates for the caller to free: there is nothing to read
/// at that address, and nothing to free.
///
/// # Safety
///
/// `token` is null or a referenced access token; `PASSIVE_LEVEL`.
unsafe fn integrity_level(token: PACCESS_TOKEN) -> Option<u32> {
    if token.is_null() {
        return None;
    }
    // Zeroed, so that the upper half stays 0 around the DWORD written into it.
    let mut level: PVOID = ptr::null_mut();
    // SAFETY: the caller's contract; a writable slot for the level.
    let status = unsafe {
        SeQueryInformationToken(
            token,
            _TOKEN_INFORMATION_CLASS::TokenIntegrityLevel,
            &raw mut level,
        )
    };
    if !NT_SUCCESS(status) {
        return None;
    }
    // A value beyond 32 bits is not a level: refused rather than trusted.
    u32::try_from(level.addr()).ok()
}

/// Why a request is refused: by the validation, or by the kernel or the attachment state.
enum Refusal {
    /// The validation in `hostmic-driver-core` refused the input.
    Rejected(Rejection),
    /// Valid input, refused with this status, for this reason.
    Status(NTSTATUS, &'static str),
    /// A request only the attached host may send, from another handle or process.
    NotHost,
}

impl Refusal {
    /// The status the request completes with.
    fn status(&self) -> NTSTATUS {
        match self {
            Self::Rejected(rejection) => rejection_status(*rejection),
            Self::Status(status, _) => *status,
            Self::NotHost => STATUS_INVALID_DEVICE_STATE,
        }
    }

    /// The reason the counters report.
    fn reason(&self) -> Reason {
        match self {
            Self::Rejected(rejection) => rejection.reason(),
            Self::Status(..) => Reason::Status,
            Self::NotHost => Reason::NotHost,
        }
    }
}

/// The largest reply: [`Stats`].
const REPLY_MAX: usize = Stats::SIZE;

/// A reply of at most [`REPLY_MAX`] bytes.
struct Reply {
    bytes: [u8; REPLY_MAX],
    len: usize,
}

impl Reply {
    const EMPTY: Self = Self {
        bytes: [0; REPLY_MAX],
        len: 0,
    };

    fn of<const N: usize>(encoded: [u8; N]) -> Self {
        const { assert!(N <= REPLY_MAX) };
        let mut bytes = [0; REPLY_MAX];
        bytes[..N].copy_from_slice(&encoded);
        Self { bytes, len: N }
    }
}

/// Refuses, counts and completes a device control request with an unknown control `code`.
///
/// # Safety
///
/// `irp` is a device control request owned by this driver, not yet completed.
unsafe fn unknown_code(irp: *mut IRP, code: u32, shared: &HostLink) -> NTSTATUS {
    let count = shared.refused(
        function(code),
        Reason::Status,
        STATUS_INVALID_DEVICE_REQUEST,
    );
    // Rate-limited as `count_refusal` does.
    if count <= 16 || count.is_power_of_two() {
        println!(
            "hostmic: unknown control code {code:#010x}, process {}",
            current_process()
        );
    }
    // SAFETY: the caller's contract.
    unsafe { complete(irp, STATUS_INVALID_DEVICE_REQUEST, 0) }
}

/// `IRP_MJ_DEVICE_CONTROL`: the host interface's requests (`hostmic-abi`), all
/// `METHOD_BUFFERED`. The I/O manager has already checked the handle's access against the
/// code's access bits.
///
/// # Safety
///
/// A device control request owned by this driver for `device`, whose stack location is
/// copied in `stack`, in the calling thread (the host interface is the top of its stack).
unsafe fn device_control(
    device: PDEVICE_OBJECT,
    irp: *mut IRP,
    stack: &IO_STACK_LOCATION,
) -> NTSTATUS {
    // SAFETY: the parameters of a device control request.
    let parameters = unsafe { stack.Parameters.DeviceIoControl };
    // SAFETY: a live host interface device (the caller's contract).
    let state = unsafe { this(device) };
    let shared = state.shared.get();
    // The six host interface codes are all METHOD_BUFFERED; for any other code (another
    // method or access among them), `SystemBuffer` need not hold the request's buffers, so it
    // is not read at all.
    if !matches!(
        parameters.IoControlCode,
        IOCTL_GET_INFO
            | IOCTL_ATTACH
            | IOCTL_GET_STREAM
            | IOCTL_ADVANCE
            | IOCTL_DETACH
            | IOCTL_GET_STATS
    ) {
        // SAFETY: the caller's contract.
        return unsafe { unknown_code(irp, parameters.IoControlCode, shared) };
    }
    let buffer = {
        // SAFETY: the caller's contract.
        let associated = unsafe { &(*irp).AssociatedIrp };
        // SAFETY: one of the six METHOD_BUFFERED codes: `SystemBuffer` is the union's member,
        // holding max(input, output) bytes, the input copied from the caller once by the I/O
        // manager.
        unsafe { associated.SystemBuffer }.cast::<u8>()
    };
    // No system buffer, no room for a reply: the output-size checks then refuse a request
    // before it changes anything (an ATTACH would otherwise map the buffer, then fail to say
    // where). The I/O manager always allocates one when a length is not 0; an IRP built by
    // other kernel code might not.
    let output = if buffer.is_null() {
        0
    } else {
        parameters.OutputBufferLength as usize
    };
    let file = stack.FileObject;
    // Gone: surprise-removed (or removed), with this handle still open.
    let gone =
        state.surprise_removed.load(Ordering::Acquire) || state.removed.load(Ordering::Acquire);
    let (name, result) = {
        let input = if buffer.is_null() || parameters.InputBufferLength == 0 {
            &[][..]
        } else {
            // SAFETY: as above; the slice ends with this block, before the reply is written.
            unsafe { slice::from_raw_parts(buffer, parameters.InputBufferLength as usize) }
        };
        match parameters.IoControlCode {
            IOCTL_GET_INFO => (
                "GET_INFO",
                host::no_input(input)
                    .and_then(|()| host::output(output, Info::SIZE))
                    .map(|()| Reply::of(host::info().to_bytes()))
                    .map_err(Refusal::Rejected),
            ),
            IOCTL_GET_STREAM => (
                "GET_STREAM",
                host::no_input(input)
                    .and_then(|()| host::output(output, StreamState::SIZE))
                    .map(|()| Reply::of(shared.snapshot().to_bytes()))
                    .map_err(Refusal::Rejected),
            ),
            IOCTL_ATTACH | IOCTL_ADVANCE if gone => (
                if parameters.IoControlCode == IOCTL_ATTACH {
                    "ATTACH"
                } else {
                    "ADVANCE"
                },
                Err(Refusal::Status(
                    STATUS_DEVICE_REMOVED,
                    "the host interface was removed",
                )),
            ),
            // SAFETY: the caller's contract.
            IOCTL_ATTACH => ("ATTACH", unsafe {
                attach(irp, file, input, output, shared)
            }),
            IOCTL_DETACH => (
                "DETACH",
                host::no_input(input)
                    .map_err(Refusal::Rejected)
                    .and_then(|()| {
                        // SAFETY: any IRQL; the requestor's process (this runs in the calling
                        // thread, the host interface being the top of its stack).
                        let requestor = unsafe { IoGetCurrentProcess() };
                        if shared.detach(file, Some(requestor)) {
                            Ok(Reply::EMPTY)
                        } else {
                            Err(Refusal::NotHost)
                        }
                    }),
            ),
            IOCTL_ADVANCE => (
                "ADVANCE",
                host::output(output, AdvanceReply::SIZE)
                    .map_err(Refusal::Rejected)
                    .and_then(|()| {
                        shared.advance(file, input).map_err(|error| match error {
                            AdvanceError::NotHost => Refusal::NotHost,
                            AdvanceError::Rejected(rejection) => Refusal::Rejected(rejection),
                        })
                    })
                    .map(|position| Reply::of(AdvanceReply { position }.to_bytes())),
            ),
            IOCTL_GET_STATS => (
                "GET_STATS",
                host::no_input(input)
                    .and_then(|()| host::output(output, Stats::SIZE))
                    .map(|()| Reply::of(shared.stats().to_bytes()))
                    .map_err(Refusal::Rejected),
            ),
            // Not reached: the code was checked above.
            // SAFETY: the caller's contract.
            code => return unsafe { unknown_code(irp, code, shared) },
        }
    };
    // SAFETY: the caller's contract; `buffer` is the request's system buffer, of at least
    // `output` bytes when not null.
    unsafe { finish(irp, buffer, shared, parameters.IoControlCode, name, result) }
}

/// Completes a host interface request with its reply, copied into the system buffer, or its
/// refusal, counted and logged.
///
/// # Safety
///
/// `irp` is a device control request owned by this driver, not yet completed, with one of the
/// six `METHOD_BUFFERED` codes; `buffer` is its `SystemBuffer`, of at least the reply's size when
/// not null (the reply is only built once the output length was checked).
unsafe fn finish(
    irp: *mut IRP,
    buffer: *mut u8,
    shared: &HostLink,
    code: u32,
    name: &str,
    result: Result<Reply, Refusal>,
) -> NTSTATUS {
    match result {
        Ok(reply) if reply.len != 0 && buffer.is_null() => {
            // Not from the I/O manager, which allocates the system buffer whenever the output
            // length is not 0: an IRP built by other kernel code.
            let refusal = Refusal::Status(STATUS_INVALID_PARAMETER, "no system buffer");
            let status = count_refusal(shared, code, name, &refusal);
            // SAFETY: the caller's contract.
            unsafe { complete(irp, status, 0) }
        }
        Ok(reply) => {
            if reply.len != 0 {
                // SAFETY: not null, and at least the reply's size (the caller's contract); the
                // slice ends before the request completes.
                let out = unsafe { slice::from_raw_parts_mut(buffer, reply.len) };
                out.copy_from_slice(&reply.bytes[..reply.len]);
            }
            // SAFETY: the caller's contract.
            unsafe { complete(irp, STATUS_SUCCESS, reply.len as u64) }
        }
        Err(refusal) => {
            let status = count_refusal(shared, code, name, &refusal);
            // SAFETY: the caller's contract.
            unsafe { complete(irp, status, 0) }
        }
    }
}

/// Counts a refused request and logs why; returns the status it completes with.
fn count_refusal(shared: &HostLink, code: u32, name: &str, refusal: &Refusal) -> NTSTATUS {
    let status = refusal.status();
    let count = shared.refused(function(code), refusal.reason(), status);
    // `ADVANCE`s refused because a state change raced the host (stale generation or position,
    // stream no longer running) are part of the protocol and may come by the hundred: counted,
    // not logged. Other refusals are logged, a foreign process's included, but any process
    // allowed to open the interface may send them in a loop: the first 16, then at every power
    // of two; the counters keep the totals.
    let race = code == IOCTL_ADVANCE
        && matches!(
            refusal.reason(),
            Reason::Generation | Reason::Position | Reason::NotRunning
        );
    if race || (count > 16 && !count.is_power_of_two()) {
        return status;
    }
    match refusal {
        Refusal::Rejected(rejection) => println!(
            "hostmic: {name} refused: {rejection:?}, process {}",
            current_process()
        ),
        Refusal::Status(_, reason) => println!(
            "hostmic: {name} refused: {reason} ({status:#010x}), process {}",
            current_process()
        ),
        Refusal::NotHost => println!(
            "hostmic: {name} refused: not the attached host's handle and process, process {}",
            current_process()
        ),
    }
    status
}

/// `IOCTL_ATTACH`: checks the request, references the host's event in its own process, and
/// attaches the handle `file` if no host is attached.
///
/// # Safety
///
/// A device control request owned by this driver, at `PASSIVE_LEVEL`, in the calling thread.
unsafe fn attach(
    irp: *mut IRP,
    file: *mut FILE_OBJECT,
    input: &[u8],
    output: usize,
    shared: &HostLink,
) -> Result<Reply, Refusal> {
    // The event handle is looked up in the current process: it must be the requestor, in
    // user mode (a filter above the interface could otherwise make it another process).
    // SAFETY: a request being processed.
    let requestor_mode = unsafe { (*irp).RequestorMode };
    // SAFETY: as above.
    let requestor = unsafe { IoGetRequestorProcess(irp) };
    // SAFETY: any IRQL.
    let current = unsafe { IoGetCurrentProcess() };
    if requestor_mode != USER_MODE || requestor != current {
        return Err(Refusal::Status(
            STATUS_ACCESS_DENIED,
            "not called from user mode in the requesting process",
        ));
    }
    // SAFETY: a request being processed.
    let wow64 = unsafe { IoIs32bitProcess(irp) } != 0;
    let request = host::attach(input, wow64).map_err(Refusal::Rejected)?;
    host::output(output, AttachReply::SIZE).map_err(Refusal::Rejected)?;
    // SAFETY: reads the kernel's exported pointer to the event object type.
    let event_type = unsafe { ExEventObjectType };
    // SAFETY: the kernel initializes it before any driver loads.
    let event_type = unsafe { *event_type };
    let mut object: PVOID = ptr::null_mut();
    // SAFETY: in the caller's process (its handle table), with a user-mode access check: only
    // an event handle of the caller that grants `EVENT_MODIFY_STATE` succeeds. The reference
    // taken is owned below.
    let status = unsafe {
        ObReferenceObjectByHandle(
            request.event as usize as HANDLE,
            EVENT_MODIFY_STATE,
            event_type,
            USER_MODE,
            &raw mut object,
            ptr::null_mut(),
        )
    };
    if !NT_SUCCESS(status) {
        return Err(Refusal::Status(status, "event handle"));
    }
    // SAFETY: PASSIVE_LEVEL, in the requesting process (checked above), which becomes the host.
    // The event's reference passes to the link, which releases it on failure.
    let address = unsafe { shared.attach(file, object.cast()) }
        .map_err(|error| Refusal::Status(error.status, error.reason))?;
    Ok(Reply::of(
        AttachReply {
            buffer: address.as_ptr() as u64,
            buffer_bytes: MAX_BUFFER_BYTES,
            reserved: 0,
        }
        .to_bytes(),
    ))
}

/// `KPROCESSOR_MODE` `UserMode`.
const USER_MODE: i8 = 1;

/// The status a refused request completes with.
fn rejection_status(rejection: Rejection) -> NTSTATUS {
    match rejection {
        Rejection::OutputSize { .. } => STATUS_BUFFER_TOO_SMALL,
        // A state change raced the host: it reads the stream again (`ERROR_NOT_READY`).
        Rejection::Generation { .. } | Rejection::Position { .. } | Rejection::NotRunning => {
            STATUS_DEVICE_NOT_READY
        }
        _ => STATUS_INVALID_PARAMETER,
    }
}

/// The calling process's id, for log messages.
fn current_process() -> usize {
    // SAFETY: any IRQL; the current process's id, as a handle value.
    let id = unsafe { PsGetCurrentProcessId() };
    id as usize
}
